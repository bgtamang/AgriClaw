def test_trailing_nulls_trimmed_and_filled_from_forecast():
    era5 = load_fixture("archive_era5_recent.json")
    fc = load_fixture("forecast_past_days.json")
    urls = []

    def fetcher(url):
        urls.append(url)
        return era5 if "archive" in url else fc

    rows, meta, notes, raw = gdd.fetch_daily(40.08, -88.24, date(2026, 10, 1), date(2026, 10, 14),
                                             model="era5", today=date(2026, 10, 15), fetcher=fetcher)
    assert [r["date"] for r in rows] == [date(2026, 10, 1) + timedelta(days=i) for i in range(14)]
    n_archive = sum(r["source"].startswith("archive") for r in rows)
    assert n_archive == 8 and sum(r["source"] == "forecast:past_days" for r in rows) == 6
    q = urllib.parse.parse_qs(urllib.parse.urlparse(urls[1]).query)
    assert q["past_days"] == ["6"] and q["forecast_days"] == ["0"]
    assert any("forecast API" in n for n in notes)


def fake_open_meteo(today, missing_tail=0):
    """Fake fetcher that returns plausible data for the requested window only."""
    calls = []

    def fetch(url):
        calls.append(url)
        q = {k: v[0] for k, v in urllib.parse.parse_qs(urllib.parse.urlparse(url).query).items()}
        if "archive" in url:
            s, e = date.fromisoformat(q["start_date"]), date.fromisoformat(q["end_date"])
            assert e < today, "archive request must not include today or future days"
        else:
            e = today - timedelta(days=1)
            s = today - timedelta(days=int(q["past_days"]))
        days = [s + timedelta(days=i) for i in range((e - s).days + 1)]
        tx = [28.0] * len(days)
        tn = [16.0] * len(days)
        if "archive" in url and missing_tail:
            tx[-missing_tail:] = [None] * missing_tail
            tn[-missing_tail:] = [None] * missing_tail
        return {"latitude": 40.1, "longitude": -88.2, "utc_offset_seconds": -18000,
                "daily_units": {"time": "iso8601", "temperature_2m_max": "°C", "temperature_2m_min": "°C"},
                "daily": {"time": [d.isoformat() for d in days], "temperature_2m_max": tx,
                          "temperature_2m_min": tn}}
    return fetch, calls


def test_in_season_end_date_is_clamped(tmp_path):
    today = date(2026, 7, 15)
    fetch, calls = fake_open_meteo(today, missing_tail=5)
    rc = gdd.main(["--lat", "40.08", "--lon", "-88.24", "--plant-date", "2026-05-01", "--crop", "corn",
                   "--out", str(tmp_path)], today=today, fetcher=fetch)
    assert rc == 0
    q = urllib.parse.parse_qs(urllib.parse.urlparse(calls[0]).query)
    assert q["end_date"] == ["2026-07-14"] and q["start_date"] == ["2026-01-01"]
    assert "past_days" in calls[1]
    with open(tmp_path / "tables" / "daily_gdd.csv", newline="", encoding="utf-8") as f:
        daily = list(csv.DictReader(f))
    assert daily[-1]["date"] == "2026-07-14"            # never beyond yesterday
    with open(tmp_path / "tables" / "corn_stages.csv", newline="", encoding="utf-8") as f:
        stages = {s["stage"]: s for s in csv.DictReader(f)}
    assert stages["R6"]["date_reached"] == "" and "not reached as of 2026-07-14" in stages["R6"]["status"]
    report = (tmp_path / "report.md").read_text(encoding="utf-8")
    assert report.index("## Warnings") < report.index("## Inputs") and "extrapolated" in report


