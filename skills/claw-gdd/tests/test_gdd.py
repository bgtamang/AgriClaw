# --- CSV input ----------------------------------------------------------------------------

def make_year_csv(path, units="C", header=("date", "tmax", "tmin")):
    rng = random.Random(7)
    rows = []
    d = date(2025, 1, 1)
    while d <= date(2025, 12, 31):
        tx = 15 + 15 * math.sin((d.timetuple().tm_yday - 105) / 365 * 2 * math.pi) + rng.uniform(-3, 3)
        tn = tx - rng.uniform(6, 14)
        if units == "F":
            tx, tn = gdd.c_to_f(tx), gdd.c_to_f(tn)
        rows.append((d.isoformat(), f"{tx:.6f}", f"{tn:.6f}"))
        d += timedelta(days=1)
    write_csv(path, rows, header)
    return rows


def test_csv_uses_planting_date(tmp_path):
    rows = make_year_csv(tmp_path / "w.csv")
    rc = gdd.main(["--input", str(tmp_path / "w.csv"), "--temp-units", "C", "--lat", "40",
                   "--plant-date", "2025-05-01", "--end-date", "2025-09-30", "--crop", "corn",
                   "--out", str(tmp_path / "o")])
    assert rc == 0
    with open(tmp_path / "o" / "tables" / "daily_gdd.csv", newline="", encoding="utf-8") as f:
        daily = list(csv.DictReader(f))
    assert daily[0]["date"] == "2025-05-01" and daily[-1]["date"] == "2025-09-30"
    expected = sum(gdd.daily_gdd(float(tx), float(tn), 10, 30, "modified")
                   for d, tx, tn in rows if "2025-05-01" <= d <= "2025-09-30")
    assert float(daily[-1]["cum_gdd_c"]) == pytest.approx(expected, abs=0.01)


def test_csv_fahrenheit_gives_same_gdd(tmp_path):
    make_year_csv(tmp_path / "c.csv", "C")
