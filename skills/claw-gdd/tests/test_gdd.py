def rows_constant(start, n, tmax, tmin):
    return [{"date": start + timedelta(days=i), "tmax_c": tmax, "tmin_c": tmin, "source": "test"}
            for i in range(n)]


def write_csv(path, rows, header=("date", "tmax", "tmin")):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)


# --- GDD equations: hand-calculated values --------------------------------------------

def test_average_method_hand_values():
    assert gdd.daily_gdd(30, 14, 10, method="average") == pytest.approx(12.0)
    assert gdd.daily_gdd(12, 2, 10, method="average") == 0.0            # mean 7 < Tbase -> 0
    assert gdd.daily_gdd(35, 21, 10, 30, method="average") == pytest.approx(18.0)  # no upper cap
    assert gdd.daily_gdd(20, 4, 10, method="average") == pytest.approx(2.0)


def test_modified_method_hand_values():
    # Tmax above Tupper is set to 30: (30 + 21)/2 - 10
    assert gdd.daily_gdd(35, 21, 10, 30, "modified") == pytest.approx(15.5)
    # Tmin below Tbase is set to 10: (20 + 10)/2 - 10 (average method would give 2.0)
    assert gdd.daily_gdd(20, 4, 10, 30, "modified") == pytest.approx(5.0)
    # both limits at once: (30 + 10)/2 - 10
    assert gdd.daily_gdd(33, 8, 10, 30, "modified") == pytest.approx(10.0)
    # whole day below Tbase
    assert gdd.daily_gdd(8, 2, 10, 30, "modified") == 0.0
    # without Tupper only the lower limit applies
    assert gdd.daily_gdd(35, 21, 10, None, "modified") == pytest.approx(18.0)
    with pytest.raises(ValueError):
        gdd.daily_gdd(20, 10, 10, 30, "sine")


def test_published_fahrenheit_examples():
    """Lee (2011) AGR-202 examples: 75/55 degF -> 15 GDD; 97/66 degF -> 26 GDD (86/50 method)."""
    for hi, lo, expected in [(75, 55, 15.0), (97, 66, 26.0)]:
        assert gdd.daily_gdd(hi, lo, 50, 86, "modified") == pytest.approx(expected)
        g_c = gdd.daily_gdd(gdd.f_to_c(hi), gdd.f_to_c(lo), 10, 30, "modified")
        assert g_c * 1.8 == pytest.approx(expected)


def test_unit_conversion():
    assert gdd.c_to_f(0) == 32 and gdd.c_to_f(30) == pytest.approx(86) and gdd.c_to_f(-40) == -40
    assert gdd.f_to_c(50) == pytest.approx(10) and gdd.f_to_c(28) == pytest.approx(-2.2222, abs=1e-4)
    rng = random.Random(42)
    for _ in range(500):
        tmax = rng.uniform(-5, 40)
        tmin = tmax - rng.uniform(0, 20)
        for method in ("average", "modified"):
            g_c = gdd.daily_gdd(tmax, tmin, 10, 30, method)
            g_f = gdd.daily_gdd(gdd.c_to_f(tmax), gdd.c_to_f(tmin), 50, 86, method)
            assert g_f == pytest.approx(1.8 * g_c, abs=1e-9)


# --- Corn stage table and timing --------------------------------------------------------

def test_stage_table_is_nch40_table3():
    """Values as printed in Neild & Newman (1987) NCH-40 Table 3, in degF-days."""
    expected = [200, 345, 475, 610, 740, 870, 1000, 1135, 1400, 1660, 1925, 2190, 2450, 2700]
    assert [s[3] for s in gdd.CORN_STAGES_NCH40] == expected
    assert [s[1] for s in gdd.CORN_STAGES_NCH40 if s[1].startswith("R")][0] == "R1"
    assert gdd.CORN_STAGES_NCH40[-1][1] == "R6"


def test_stage_timing_constant_weather():
    # 30/20 degC -> 15 degC-days = 27 degF-days per day, planting day counted as day 1
    plant = date(2025, 5, 1)
    rows = rows_constant(plant, 120, 30.0, 20.0)
    daily = gdd.accumulate_gdd(rows, plant, plant + timedelta(days=119), 10, 30, "modified", 40.0)
    stages = gdd.corn_stages(daily)
    for s in stages:
        day = math.ceil(s["gdd_f_table"] / 27.0 - 1e-12)
        assert s["days_after_planting"] == day, s
        assert s["date_reached"] == (plant + timedelta(days=day - 1)).isoformat()
    r1 = next(s for s in stages if s["stage"] == "R1")
    # the old bug compared degF thresholds with degC-days: silking would be day ceil(1400/15) = 94
    assert r1["days_after_planting"] == 52 != math.ceil(1400 / 15)


def test_hybrid_scaling_and_no_extrapolation():
    plant = date(2025, 5, 1)
    daily = gdd.accumulate_gdd(rows_constant(plant, 60, 30.0, 20.0), plant,
                               plant + timedelta(days=59), 10, 30, "modified", 40.0)
    stages = {s["stage"]: s for s in gdd.corn_stages(daily, hybrid_rating_f=2400)}
    assert stages["R1"]["gdd_f_used"] == pytest.approx(1400 * 2400 / 2700, abs=0.05)
    assert stages["R1"]["days_after_planting"] == math.ceil(1400 * 2400 / 2700 / 27)
    # 60 days x 27 = 1620 degF-days: R6 is reported as not reached, never extrapolated
    assert stages["R6"]["date_reached"] == ""
    assert stages["R6"]["status"].startswith("not reached as of")


# --- Daylength --------------------------------------------------------------------------

def test_daylength_matches_open_meteo_within_5_minutes():
    resp = load_fixture("archive_daylight_champaign_2025.json")
    lat = resp["latitude"]
    worst = 0.0
    for t, s in zip(resp["daily"]["time"], resp["daily"]["daylight_duration"]):
        doy = date.fromisoformat(t).timetuple().tm_yday
        worst = max(worst, abs(gdd.daylength_hours(lat, doy) - s / 3600.0))
    assert worst * 60 < 5.0


def test_daylength_properties():
    assert gdd.daylength_hours(0.0, 80) == pytest.approx(12.1, abs=0.1)     # equator, refraction
    assert gdd.daylength_hours(75.0, 172) == 24.0                            # polar day
    assert gdd.daylength_hours(75.0, 355) == 0.0                             # polar night
    assert gdd.daylength_hours(40.0, 172, 6.0) > gdd.daylength_hours(40.0, 172)
    north, south = gdd.daylength_hours(40.0, 172), gdd.daylength_hours(-40.0, 172)
    assert south < 12 < north and 24.0 < north + south < 24.5   # refraction lengthens both days


