def test_missing_values_are_counted_not_zeroed():
    rows = mkrows([5.0, None, 0.0, 0.0, None, 12.0])
    s = wx.summarize(rows)
    assert s["total_precip_mm"] == 17.0 and s["n_missing_precip_mm"] == 2 and s["complete"] == "no"
    assert s["n_days_p_and_et0"] == 4 and s["p_minus_et0_mm"] == pytest.approx(17.0 - 16.0)
    spells = wx.dry_spells(rows)
    # the two dry days (06-03, 06-04) sit between missing and missing: one spell, flagged
    assert [(sp["length_days"], sp["touches_missing"]) for sp in spells] == [(2, "yes")]


def test_dry_and_wet_spell_definitions():
    rows = mkrows([0.0, 0.5, 0.9, 1.0, 0.0, 0.0, 0.0, 2.0, 3.0])
    spells = wx.dry_spells(rows)
    assert sorted(sp["length_days"] for sp in spells) == [3, 3]      # 1.0 mm is a wet day (ETCCDI)
    assert spells[0]["touches_period_edge"] == "yes"                 # first run starts at the period edge
    assert sorted(wx.wet_spells(rows)) == [1, 2]


def test_threshold_boundaries():
    rows = mkrows([10.0, 9.99, 20.0, 0.0, 0.0, 0.0],
                  tmax=[25.0, 25.1, 32.2, 32.3, 35.0, 34.99],
                  tmin=[0.0, -0.1, -2.23, -2.2, 20.0, 20.1])
    table, events, _ = wx.threshold_indices(rows)
    t = {r["index"]: r["days"] for r in table}
    assert t["FD"] == 3          # TN < 0 is strict: 0.0 is not a frost day
    assert t["HF28"] == 1        # TN <= 28 degF (-2.22 degC): -2.23 yes, -2.2 no
    assert t["SU"] == 5          # TX > 25 strict: 25.0 is not a summer day
    assert t["TR"] == 1          # TN > 20 strict
    assert t["TX90F"] == 3       # TX > 90 degF = 32.22 degC
    assert t["TX95F"] == 1       # TX >= 35 degC
    assert t["R10mm"] == 2 and t["R20mm"] == 1 and t["Rx1day"] == 20.0
    assert any(e["index"] == "TX95F" and e["date"] == "2025-06-05" for e in events)


def test_trailing_nulls_trimmed_and_filled_from_forecast():
    era5, fc = fixture("archive_era5_recent.json"), fixture("forecast_past_days.json")
    urls = []

    def fetcher(url):
        urls.append(url)
        return era5 if "archive" in url else fc

    rows, meta, notes, _ = wx.fetch_daily(40.08, -88.24, date(2026, 10, 1), date(2026, 10, 31), "era5",
                                          today=date(2026, 10, 15), fetcher=fetcher)
    q = urllib.parse.parse_qs(urllib.parse.urlparse(urls[0]).query)
    assert q["end_date"] == ["2026-10-14"]                       # clamped to yesterday, never the future
    assert rows[-1]["date"] == date(2026, 10, 14) and len(rows) == 14
    assert [r["source"] for r in rows].count("forecast:past_days") == 6
    assert any("after the last complete day" in n for n in notes)


def test_cli_in_season_run_with_fake_api(tmp_path):
    today = date(2026, 7, 20)

    def fetcher(url):
        q = {k: v[0] for k, v in urllib.parse.parse_qs(urllib.parse.urlparse(url).query).items()}
        if "archive" in url:
            s, e = date.fromisoformat(q["start_date"]), date.fromisoformat(q["end_date"])
            assert e < today
        else:
            s, e = today - timedelta(days=int(q["past_days"])), today - timedelta(days=1)
        days = [s + timedelta(days=i) for i in range((e - s).days + 1)]
        n = len(days)
        daily = {"time": [d.isoformat() for d in days]}
        for var, val in (("temperature_2m_max", 30.0), ("temperature_2m_min", 18.0), ("precipitation_sum", 0.0),
                         ("et0_fao_evapotranspiration", 5.0), ("relative_humidity_2m_min", 40.0),
                         ("wind_speed_10m_mean", 3.0), ("shortwave_radiation_sum", 22.0)):
            daily[var] = [val] * n
        if "archive" in url:
            daily["precipitation_sum"][-3:] = [None] * 3       # pretend precipitation lags
        return {"latitude": 40.1, "longitude": -88.2, "utc_offset_seconds": -18000, "daily": daily,
                "daily_units": {"temperature_2m_max": "°C", "temperature_2m_min": "°C", "precipitation_sum": "mm",
                                "et0_fao_evapotranspiration": "mm", "relative_humidity_2m_min": "%",
                                "wind_speed_10m_mean": "m/s", "shortwave_radiation_sum": "MJ/m²"}}

    rc = wx.main(["--lat", "40.08", "--lon", "-88.24", "--start-date", "2026-05-01", "--end-date",
                  "2026-10-31", "--out", str(tmp_path)], today=today, fetcher=fetcher)
    assert rc == 0
    with open(tmp_path / "tables" / "season_summary.csv", newline="", encoding="utf-8") as f:
        s = next(csv.DictReader(f))
    assert s["n_days"] == str((date(2026, 7, 19) - date(2026, 5, 1)).days + 1)
    assert s["n_missing_precip_mm"] == "3"                   # counted, not zero-filled
    rep = (tmp_path / "report.md").read_text(encoding="utf-8")
    assert rep.index("## Warnings") < rep.index("## Data source") and "never treated as zero" in rep


def write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def test_station_csv_units_and_conversion(tmp_path):
    write_csv(tmp_path / "s.csv", ["date", "tmax", "tmin", "precip", "wind_10m_m_s"],
              [["2025-06-01", "86", "50", "1.0", "3.2"], ["2025-06-02", "95", "68", "", "2.0"]])
    rows = wx.read_station_csv(str(tmp_path / "s.csv"), "F", "in")
    assert rows[0]["tmax_c"] == pytest.approx(30.0) and rows[0]["tmin_c"] == pytest.approx(10.0)
    assert rows[0]["precip_mm"] == pytest.approx(25.4) and rows[1]["precip_mm"] is None
    assert rows[0]["wind_2m_m_s"] == pytest.approx(2.4, abs=0.01)
    with pytest.raises(ValueError, match="--precip-units"):
        wx.read_station_csv(str(tmp_path / "s.csv"), "F", None)
    write_csv(tmp_path / "t.csv", ["date", "tmax_c", "tmin_c"], [["2025-06-01", "30", "10"]])
    with pytest.raises(ValueError, match="--temp-units"):
        wx.read_station_csv(str(tmp_path / "t.csv"), "F", None)


def test_station_csv_missing_dates_counted(tmp_path):
    write_csv(tmp_path / "s.csv", ["date", "tmax", "tmin", "precip"],
              [["2025-06-01", "30", "15", "0"], ["2025-06-04", "31", "16", "4"]])
    rc = wx.main(["--input", str(tmp_path / "s.csv"), "--temp-units", "C", "--precip-units", "mm",
                  "--start-date", "2025-06-01", "--end-date", "2025-06-04", "--out", str(tmp_path / "o")])
    assert rc == 0
    with open(tmp_path / "o" / "tables" / "season_summary.csv", newline="", encoding="utf-8") as f:
        s = next(csv.DictReader(f))
    assert s["n_days"] == "4" and s["n_missing_precip_mm"] == "2" and s["total_precip_mm"] == "4.0"
    assert "Open-Meteo's archive is gridded" not in (tmp_path / "o" / "report.md").read_text(encoding="utf-8")


def test_cli_demo(tmp_path):
    r = subprocess.run([sys.executable, str(SCRIPT), "--demo", "--out", str(tmp_path)],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    for f in ["report.md", "tables/daily_weather.csv", "tables/monthly_summary.csv", "tables/season_summary.csv",
              "tables/threshold_indices.csv", "tables/dry_spells.csv", "figures/temp_precip.png",
              "figures/water_balance.png", "figures/monthly_summary.png", "reproducibility/commands.sh",
              "reproducibility/environment.txt", "reproducibility/checksums.sha256"]:
        assert (tmp_path / f).is_file(), f
    # totals equal an independent sum of the bundled response for April 1 - October 31, 2025
    d = json.loads((SKILL_DIR / "demo" / "openmeteo_champaign_2025.json").read_text(encoding="utf-8"))["daily"]
    idx = [i for i, t in enumerate(d["time"]) if "2025-04-01" <= t <= "2025-10-31"]
    with open(tmp_path / "tables" / "season_summary.csv", newline="", encoding="utf-8") as f:
        s = next(csv.DictReader(f))
    assert float(s["total_precip_mm"]) == pytest.approx(sum(d["precipitation_sum"][i] for i in idx), abs=0.05)
    assert float(s["total_et0_mm"]) == pytest.approx(sum(d["et0_fao_evapotranspiration"][i] for i in idx), abs=0.05)
    with open(tmp_path / "tables" / "daily_weather.csv", newline="", encoding="utf-8") as f:
        cols = next(csv.reader(f))
    assert {"date", "precip_mm", "et0_mm", "rh_min_pct", "wind_2m_m_s"} <= set(cols)  # claw-water-balance input
    rep = (tmp_path / "report.md").read_text(encoding="utf-8")
    assert "40.0800°N, 88.2400°W" in rep and "not a drought index" in rep
