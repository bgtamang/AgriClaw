def test_wind_height_conversion_fao56_example14():
    # FAO-56 Example 14: 3.2 m/s at 10 m -> 2.4 m/s at 2 m (factor 0.75 rounded)
    assert wx.wind_to_2m(3.2, 10) == pytest.approx(2.4, abs=0.01)
    assert wx.wind_to_2m(1.0, 2) == pytest.approx(1.0, abs=0.001)


