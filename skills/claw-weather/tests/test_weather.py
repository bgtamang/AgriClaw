def fixture(name):
    return json.loads((FIX / name).read_text(encoding="utf-8"))


def mkrows(precip, tmax=None, tmin=None, start=date(2025, 6, 1)):
    n = len(precip)
    tmax = tmax or [25.0] * n
    tmin = tmin or [15.0] * n
    return [{"date": start + timedelta(days=i), "tmax_c": tmax[i], "tmin_c": tmin[i], "precip_mm": precip[i],
             "et0_mm": 4.0, "rh_min_pct": 45.0, "wind_2m_m_s": 2.0, "srad_mj_m2": 20.0, "source": "test"}
            for i in range(n)]


